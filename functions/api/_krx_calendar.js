// 한국거래소(KRX) 휴장일 — 주말 + 아래 날짜(공휴일 · 대체공휴일 · 선거일 · 근로자의날 · 연말 12/31).
// 단타(클로드) ①② 는 장이 열리는 날인지 먼저 보고, 휴장이면 시세 조회·주문을 하지 않는다(2026-10-05 개천절 대체휴일에 주문이 나가 거절된 일 대응).
// 해마다 거래소 휴장일 공지로 다음 해 목록을 더한다 — 회귀가 '내년 목록이 있는지'를 검사한다.
export const KRX_HOLIDAYS = {
  2026: ["2026-01-01", "2026-02-16", "2026-02-17", "2026-02-18", "2026-03-02", "2026-05-01", "2026-05-05", "2026-05-25", "2026-06-03",
    "2026-08-17", "2026-09-24", "2026-09-25", "2026-10-05", "2026-10-09", "2026-12-25", "2026-12-31"],
  2027: ["2027-01-01", "2027-02-05", "2027-02-08", "2027-03-01", "2027-05-05", "2027-05-13", "2027-08-16", "2027-09-14", "2027-09-15",
    "2027-09-16", "2027-10-04", "2027-10-11", "2027-12-27", "2027-12-31"],
};
const SET = new Set(Object.values(KRX_HOLIDAYS).flat());
// {closed, reason, known} — known=false 면 목록이 없는 해(평일은 연다고 보고, 장부에 '휴장일 목록 없음'을 남긴다)
export function krxDay(date) {
  const d = String(date || ""), y = d.slice(0, 4);
  const wd = new Date(d + "T00:00:00Z").getUTCDay();
  if (wd === 0 || wd === 6) return { closed: true, reason: "weekend", known: true };
  if (SET.has(d)) return { closed: true, reason: "krx_holiday", known: true };
  return { closed: false, reason: "", known: !!KRX_HOLIDAYS[y] };
}
